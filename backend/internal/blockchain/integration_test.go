func TestRecordDonationOnHardhat(t *testing.T) {
	if os.Getenv("RUN_BLOCKCHAIN_INTEGRATION") != "1" {
		t.Skip("set RUN_BLOCKCHAIN_INTEGRATION=1 to run Hardhat integration tests")
	}

	// Determine the absolute path of this test file.
	_, currentFile, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("failed to determine current test file path")
	}

	// Current file:
	// backend/internal/blockchain/integration_test.go
	//
	// Move two levels up:
	// backend/internal/blockchain
	//              -> backend/internal
	//              -> backend
	backendDir := filepath.Join(
		filepath.Dir(currentFile),
		"..",
		"..",
	)

	projectDir := filepath.Join(
		backendDir,
		"..",
	)

	// Load backend/.env using an absolute path.
	envPath := filepath.Join(
		backendDir,
		".env",
	)

	if err := godotenv.Load(envPath); err != nil {
		t.Fatalf("failed to load .env: %v", err)
	}

	privateKey := os.Getenv("BLOCKCHAIN_PRIVATE_KEY")
	rpcURL := os.Getenv("BLOCKCHAIN_RPC_URL")
	contractAddress := os.Getenv("BLOCKCHAIN_CONTRACT_ADDRESS")

	if privateKey == "" {
		t.Fatal("BLOCKCHAIN_PRIVATE_KEY is not configured")
	}

	if rpcURL == "" {
		t.Fatal("BLOCKCHAIN_RPC_URL is not configured")
	}

	if contractAddress == "" {
		t.Fatal("BLOCKCHAIN_CONTRACT_ADDRESS is not configured")
	}

	ctx := context.Background()

	// Connect to Hardhat RPC.
	client, err := NewClient(rpcURL)
	if err != nil {
		t.Fatalf("failed to connect to blockchain: %v", err)
	}
	defer client.Close()

	// Get the actual chain ID from the RPC.
	chainID, err := client.Eth.ChainID(ctx)
	if err != nil {
		t.Fatalf("failed to get chain ID: %v", err)
	}

	t.Logf("chain ID: %s", chainID.String())

	// Create Ethereum signer from the private key.
	signer, err := NewSigner(privateKey, chainID)
	if err != nil {
		t.Fatalf("failed to create signer: %v", err)
	}

	t.Logf("signer address: %s", signer.Address.Hex())

	// Load the deployed contract ABI.
	abiPath := filepath.Join(
		backendDir,
		"internal",
		"blockchain",
		"abi",
		"DonationRegistry.json",
	)

	contract, err := LoadContract(
		contractAddress,
		abiPath,
	)
	if err != nil {
		t.Fatalf("failed to load contract: %v", err)
	}

	// Create contract registry wrapper.
	registry, err := NewRegistry(client, contract)
	if err != nil {
		t.Fatalf("failed to create registry: %v", err)
	}

	// Test campaign ID.
	campaignID := common.HexToHash(
		"0x6f76b55b5fb7db5ae822c5f21fa38d28a97b75e8c85d78ce14967d5bfb6677ff",
	)

	// The ZK circuit uses campaign_max = 5,000,000.
	campaignMax := big.NewInt(5000000)

	// ---------------------------------------------------------------------
	// 1. Register campaign max donation on-chain.
	// ---------------------------------------------------------------------

	setCampaignData, err := registry.Contract.ABI.Pack(
		"setCampaignMaxDonation",
		campaignID,
		campaignMax,
	)
	if err != nil {
		t.Fatalf(
			"failed to pack setCampaignMaxDonation: %v",
			err,
		)
	}

	setCampaignTx, err := BuildSignedTransaction(
		ctx,
		client,
		signer,
		registry.Address,
		setCampaignData,
		big.NewInt(0),
	)
	if err != nil {
		t.Fatalf(
			"failed to build campaign registration transaction: %v",
			err,
		)
	}

	if err := SendTransaction(
		ctx,
		client,
		setCampaignTx,
	); err != nil {
		t.Fatalf(
			"failed to send campaign registration transaction: %v",
			err,
		)
	}

	setCampaignReceipt, err := WaitForTransaction(
		ctx,
		client,
		setCampaignTx,
	)
	if err != nil {
		t.Fatalf(
			"failed to wait for campaign registration transaction: %v",
			err,
		)
	}

	if setCampaignReceipt.Status != 1 {
		t.Fatalf(
			"campaign registration failed: status=%d",
			setCampaignReceipt.Status,
		)
	}

	t.Logf(
		"campaign max registered: campaign=%s max=%s tx=%s",
		campaignID.Hex(),
		campaignMax.String(),
		setCampaignTx.Hash().Hex(),
	)

	// ---------------------------------------------------------------------
	// 2. Load the real Groth16 proof generated by snarkjs.
	// ---------------------------------------------------------------------

	proofPath := filepath.Join(
		projectDir,
		"zk",
		"build",
		"donation-proof.json",
	)

	publicPath := filepath.Join(
		projectDir,
		"zk",
		"build",
		"donation-public.json",
	)

	proofData, err := os.ReadFile(proofPath)
	if err != nil {
		t.Fatalf(
			"failed to read ZK proof: %v",
			err,
		)
	}

	publicData, err := os.ReadFile(publicPath)
	if err != nil {
		t.Fatalf(
			"failed to read ZK public inputs: %v",
			err,
		)
	}

	var proof integrationZKProof

	if err := json.Unmarshal(proofData, &proof); err != nil {
		t.Fatalf(
			"failed to parse ZK proof: %v",
			err,
		)
	}

	var publicSignals []string

	if err := json.Unmarshal(
		publicData,
		&publicSignals,
	); err != nil {
		t.Fatalf(
			"failed to parse ZK public inputs: %v",
			err,
		)
	}

	if len(publicSignals) != 2 {
		t.Fatalf(
			"expected 2 public signals, got %d",
			len(publicSignals),
		)
	}

	// Public signals:
	//
	// [0] campaign_max
	// [1] commitment
	proofCampaignMax, ok := new(big.Int).SetString(
		publicSignals[0],
		10,
	)
	if !ok {
		t.Fatal("invalid campaign_max public signal")
	}

	commitmentInt, ok := new(big.Int).SetString(
		publicSignals[1],
		10,
	)
	if !ok {
		t.Fatal("invalid commitment public signal")
	}

	if proofCampaignMax.Cmp(campaignMax) != 0 {
		t.Fatalf(
			"unexpected campaign max: got %s, want %s",
			proofCampaignMax.String(),
			campaignMax.String(),
		)
	}

	commitment := common.BytesToHash(
		commitmentInt.Bytes(),
	)

	t.Logf(
		"commitment: %s",
		commitmentInt.String(),
	)

	// ---------------------------------------------------------------------
	// 3. Convert snarkjs proof into Solidity verifier arguments.
	// ---------------------------------------------------------------------

	if len(proof.PiA) < 2 {
		t.Fatal("invalid proof: pi_a")
	}

	if len(proof.PiB) < 2 ||
		len(proof.PiB[0]) < 2 ||
		len(proof.PiB[1]) < 2 {
		t.Fatal("invalid proof: pi_b")
	}

	if len(proof.PiC) < 2 {
		t.Fatal("invalid proof: pi_c")
	}

	pA0, ok := new(big.Int).SetString(proof.PiA[0], 10)
	if !ok {
		t.Fatal("invalid proof: pi_a[0]")
	}

	pA1, ok := new(big.Int).SetString(proof.PiA[1], 10)
	if !ok {
		t.Fatal("invalid proof: pi_a[1]")
	}

	pB00, ok := new(big.Int).SetString(proof.PiB[0][1], 10)
	if !ok {
		t.Fatal("invalid proof: pi_b[0][1]")
	}

	pB01, ok := new(big.Int).SetString(proof.PiB[0][0], 10)
	if !ok {
		t.Fatal("invalid proof: pi_b[0][0]")
	}

	pB10, ok := new(big.Int).SetString(proof.PiB[1][1], 10)
	if !ok {
		t.Fatal("invalid proof: pi_b[1][1]")
	}

	pB11, ok := new(big.Int).SetString(proof.PiB[1][0], 10)
	if !ok {
		t.Fatal("invalid proof: pi_b[1][0]")
	}

	pC0, ok := new(big.Int).SetString(proof.PiC[0], 10)
	if !ok {
		t.Fatal("invalid proof: pi_c[0]")
	}

	pC1, ok := new(big.Int).SetString(proof.PiC[1], 10)
	if !ok {
		t.Fatal("invalid proof: pi_c[1]")
	}

	pA := [2]*big.Int{
		pA0,
		pA1,
	}

	pB := [2][2]*big.Int{
		{
			pB00,
			pB01,
		},
		{
			pB10,
			pB11,
		},
	}

	pC := [2]*big.Int{
		pC0,
		pC1,
	}

	pubSignalsArgs := [2]*big.Int{
		proofCampaignMax,
		commitmentInt,
	}

	// ---------------------------------------------------------------------
	// 4. Prepare encrypted amount.
	//
	// This integration test focuses on blockchain + Groth16 verification.
	// The actual Paillier ciphertext is tested separately by the backend
	// crypto tests and donation service.
	// ---------------------------------------------------------------------

	encryptedAmount := []byte(
		"paillier-ciphertext-test",
	)

	// ---------------------------------------------------------------------
	// 5. Encode recordDonation(...) call.
	// ---------------------------------------------------------------------

	data, err := registry.PackRecordDonation(
		campaignID,
		commitment,
		encryptedAmount,
		pA,
		pB,
		pC,
		pubSignalsArgs,
	)
	if err != nil {
		t.Fatalf(
			"failed to pack donation: %v",
			err,
		)
	}

	// Estimate gas before creating the transaction.
	estimatedGas, err := client.Eth.EstimateGas(
		ctx,
		ethereum.CallMsg{
			From: signer.Address,
			To:   &registry.Address,
			Data: data,
		},
	)
	if err != nil {
		t.Fatalf(
			"failed to estimate gas: %v",
			err,
		)
	}

	t.Logf(
		"estimated gas: %d",
		estimatedGas,
	)

	// ---------------------------------------------------------------------
	// 6. Build and sign transaction.
	// ---------------------------------------------------------------------

	tx, err := BuildSignedTransaction(
		ctx,
		client,
		signer,
		registry.Address,
		data,
		big.NewInt(0),
	)
	if err != nil {
		t.Fatalf(
			"failed to build transaction: %v",
			err,
		)
	}

	if tx.Gas() < estimatedGas {
		t.Fatalf(
			"transaction gas limit is too low: got %d, estimated %d",
			tx.Gas(),
			estimatedGas,
		)
	}

	t.Logf(
		"transaction nonce: %d",
		tx.Nonce(),
	)

	t.Logf(
		"transaction hash: %s",
		tx.Hash().Hex(),
	)

	// ---------------------------------------------------------------------
	// 7. Send transaction to Hardhat.
	// ---------------------------------------------------------------------

	if err := SendTransaction(
		ctx,
		client,
		tx,
	); err != nil {
		t.Fatalf(
			"failed to send transaction: %v",
			err,
		)
	}

	// ---------------------------------------------------------------------
	// 8. Wait until transaction is mined.
	// ---------------------------------------------------------------------

	receipt, err := WaitForTransaction(
		ctx,
		client,
		tx,
	)
	if err != nil {
		t.Fatalf(
			"failed to wait for transaction: %v",
			err,
		)
	}

	if receipt.Status != 1 {
		t.Fatalf(
			"transaction failed on chain: status=%d",
			receipt.Status,
		)
	}

	t.Logf(
		"transaction confirmed: hash=%s block=%d",
		tx.Hash().Hex(),
		receipt.BlockNumber.Uint64(),
	)
}


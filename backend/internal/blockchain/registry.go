package blockchain

import (
	"context"
	"encoding/json"
	"fmt"
	"math/big"

	"github.com/ethereum/go-ethereum/common"
	"github.com/ethereum/go-ethereum/crypto"

	"github.com/izagoto/zk-paillier-donation-system/internal/zk"
)

type Registry struct {
	Client   *Client
	Contract *Contract
	Address  common.Address
}

func NewRegistry(
	client *Client,
	contract *Contract,
) (*Registry, error) {
	if client == nil {
		return nil, fmt.Errorf("blockchain client is required")
	}

	if contract == nil {
		return nil, fmt.Errorf("contract is required")
	}

	if !common.IsHexAddress(contract.Address) {
		return nil, fmt.Errorf("invalid contract address")
	}

	return &Registry{
		Client:   client,
		Contract: contract,
		Address:  common.HexToAddress(contract.Address),
	}, nil
}

func (r *Registry) PackRecordDonation(
	campaignID [32]byte,
	commitment [32]byte,
	encryptedAmount []byte,
	pA [2]*big.Int,
	pB [2][2]*big.Int,
	pC [2]*big.Int,
	pubSignals [2]*big.Int,
) ([]byte, error) {
	data, err := r.Contract.ABI.Pack(
		"recordDonation",
		campaignID,
		commitment,
		encryptedAmount,
		pA,
		pB,
		pC,
		pubSignals,
	)
	if err != nil {
		return nil, fmt.Errorf(
			"failed to pack recordDonation call: %w",
			err,
		)
	}

	return data, nil
}

func (r *Registry) RecordDonation(
	ctx context.Context,
	signer *Signer,
	payload DonationPayload,
) (string, error) {
	if signer == nil {
		return "", fmt.Errorf("signer is required")
	}

	if payload.CampaignID == "" {
		return "", fmt.Errorf("campaign ID is required")
	}

	if payload.CampaignMax == "" {
		return "", fmt.Errorf("campaign max is required")
	}

	if payload.Commitment == "" {
		return "", fmt.Errorf("commitment is required")
	}

	if payload.ZKProof == "" {
		return "", fmt.Errorf("zk proof is required")
	}

	// Convert the campaign UUID into the same bytes32 representation
	// used by the rest of the blockchain integration.
	campaignID := crypto.Keccak256Hash(
		[]byte(payload.CampaignID),
	)

	commitmentInt, ok := new(big.Int).SetString(
		payload.Commitment,
		10,
	)
	if !ok {
		return "", fmt.Errorf("invalid commitment")
	}

	if commitmentInt.Sign() < 0 {
		return "", fmt.Errorf("commitment must not be negative")
	}

	commitmentBytes := common.BytesToHash(
		commitmentInt.Bytes(),
	)

	campaignMax, ok := new(big.Int).SetString(
		payload.CampaignMax,
		10,
	)
	if !ok {
		return "", fmt.Errorf("invalid campaign max")
	}

	if campaignMax.Sign() <= 0 {
		return "", fmt.Errorf("campaign max must be greater than zero")
	}

	// Parse the Groth16 proof generated by snarkjs.
	var proof zk.Proof

	if err := json.Unmarshal(
		[]byte(payload.ZKProof),
		&proof,
	); err != nil {
		return "", fmt.Errorf(
			"failed to parse zk proof: %w",
			err,
		)
	}

	// Validate proof structure before converting values.
	if len(proof.PiA) < 2 {
		return "", fmt.Errorf("invalid zk proof: pi_a")
	}

	if len(proof.PiB) < 2 ||
		len(proof.PiB[0]) < 2 ||
		len(proof.PiB[1]) < 2 {
		return "", fmt.Errorf("invalid zk proof: pi_b")
	}

	if len(proof.PiC) < 2 {
		return "", fmt.Errorf("invalid zk proof: pi_c")
	}

	// Convert snarkjs decimal strings into big.Int values.
	pA0, ok := new(big.Int).SetString(proof.PiA[0], 10)
	if !ok {
		return "", fmt.Errorf("invalid zk proof: pi_a[0]")
	}

	pA1, ok := new(big.Int).SetString(proof.PiA[1], 10)
	if !ok {
		return "", fmt.Errorf("invalid zk proof: pi_a[1]")
	}

	pB00, ok := new(big.Int).SetString(proof.PiB[0][1], 10)
	if !ok {
		return "", fmt.Errorf("invalid zk proof: pi_b[0][1]")
	}

	pB01, ok := new(big.Int).SetString(proof.PiB[0][0], 10)
	if !ok {
		return "", fmt.Errorf("invalid zk proof: pi_b[0][0]")
	}

	pB10, ok := new(big.Int).SetString(proof.PiB[1][1], 10)
	if !ok {
		return "", fmt.Errorf("invalid zk proof: pi_b[1][1]")
	}

	pB11, ok := new(big.Int).SetString(proof.PiB[1][0], 10)
	if !ok {
		return "", fmt.Errorf("invalid zk proof: pi_b[1][0]")
	}

	pC0, ok := new(big.Int).SetString(proof.PiC[0], 10)
	if !ok {
		return "", fmt.Errorf("invalid zk proof: pi_c[0]")
	}

	pC1, ok := new(big.Int).SetString(proof.PiC[1], 10)
	if !ok {
		return "", fmt.Errorf("invalid zk proof: pi_c[1]")
	}

	pA := [2]*big.Int{
		pA0,
		pA1,
	}

	// snarkjs uses a different representation/order for G2
	// coordinates than the Solidity verifier expects.
	pB := [2][2]*big.Int{
		{
			pB00,
			pB01,
		},
		{
			pB10,
			pB11,
		},
	}

	pC := [2]*big.Int{
		pC0,
		pC1,
	}

	// The public signals must match the exact order declared
	// in DonationProof.circom:
	//
	// 1. campaign_max
	// 2. commitment
	pubSignals := [2]*big.Int{
		campaignMax,
		commitmentInt,
	}

	data, err := r.PackRecordDonation(
		campaignID,
		commitmentBytes,
		[]byte(payload.EncryptedAmount),
		pA,
		pB,
		pC,
		pubSignals,
	)
	if err != nil {
		return "", err
	}

	tx, err := BuildSignedTransaction(
		ctx,
		r.Client,
		signer,
		r.Address,
		data,
		big.NewInt(0),
	)
	if err != nil {
		return "", err
	}

	if err := SendTransaction(
		ctx,
		r.Client,
		tx,
	); err != nil {
		return "", err
	}

	receipt, err := WaitForTransaction(
		ctx,
		r.Client,
		tx,
	)
	if err != nil {
		return "", err
	}

	if receipt.Status != 1 {
		return "", fmt.Errorf(
			"blockchain transaction failed: %s",
			tx.Hash().Hex(),
		)
	}

	return tx.Hash().Hex(), nil
}

func donationIDToBigInt(id uint64) *big.Int {
	return new(big.Int).SetUint64(id)
}

func (r *Registry) SetCampaignMaxDonation(
	ctx context.Context,
	signer *Signer,
	campaignID string,
	maxDonation string,
) (string, error) {
	if signer == nil {
		return "", fmt.Errorf("signer is required")
	}

	if campaignID == "" {
		return "", fmt.Errorf("campaign ID is required")
	}

	if maxDonation == "" {
		return "", fmt.Errorf("max donation is required")
	}

	campaignMax, ok := new(big.Int).SetString(
		maxDonation,
		10,
	)
	if !ok {
		return "", fmt.Errorf("invalid max donation")
	}

	if campaignMax.Sign() <= 0 {
		return "", fmt.Errorf(
			"max donation must be greater than zero",
		)
	}

	onChainCampaignID := crypto.Keccak256Hash(
		[]byte(campaignID),
	)

	data, err := r.Contract.ABI.Pack(
		"setCampaignMaxDonation",
		onChainCampaignID,
		campaignMax,
	)
	if err != nil {
		return "", fmt.Errorf(
			"failed to pack setCampaignMaxDonation call: %w",
			err,
		)
	}

	tx, err := BuildSignedTransaction(
		ctx,
		r.Client,
		signer,
		r.Address,
		data,
		big.NewInt(0),
	)
	if err != nil {
		return "", err
	}

	if err := SendTransaction(
		ctx,
		r.Client,
		tx,
	); err != nil {
		return "", err
	}

	receipt, err := WaitForTransaction(
		ctx,
		r.Client,
		tx,
	)
	if err != nil {
		return "", err
	}

	if receipt.Status != 1 {
		return "", fmt.Errorf(
			"blockchain transaction failed: %s",
			tx.Hash().Hex(),
		)
	}

	return tx.Hash().Hex(), nil
}
